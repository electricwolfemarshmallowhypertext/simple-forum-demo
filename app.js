function bindEvents() {
  els.channelList.addEventListener("click", (event) => {
    const button = event.target.closest("[data-channel]");
    if (!button) return;
    state.channel = button.dataset.channel;
    playTone("tap");
    renderChannels();
    renderThreads();
  });

  els.tagStrip.addEventListener("click", (event) => {
    const button = event.target.closest("[data-tag]");
    if (!button) return;
    state.tag = button.dataset.tag;
    playTone("tap");
    renderTags();
    renderThreads();
  });

  document.querySelectorAll(".segment").forEach((button) => {
    button.addEventListener("click", () => {
      state.sort = button.dataset.sort;
      document.querySelectorAll(".segment").forEach((segment) => segment.classList.remove("active"));
      button.classList.add("active");
      playTone("tap");
      renderThreads();
    });
  });

  els.searchInput.addEventListener("input", (event) => {
    state.query = event.target.value;
    renderThreads();
  });

  els.threadList.addEventListener("click", (event) => {
    const openButton = event.target.closest("[data-open-thread]");
    const reactionButton = event.target.closest("[data-reaction]");

    if (openButton) {
      openThread(openButton.dataset.openThread);
      return;
    }

    if (reactionButton) {
      toggleReaction(reactionButton.dataset.threadId, reactionButton.dataset.reaction, event);
    }
  });

  document.querySelectorAll("[data-close-modal]").forEach((button) => button.addEventListener("click", closeThread));
  document.querySelectorAll("[data-close-composer]").forEach((button) => button.addEventListener("click", closeComposer));
  document.querySelector("#openComposer").addEventListener("click", openComposer);
  document.querySelector("#quickComposer").addEventListener("click", openComposer);
  document.querySelector("#quickComposerText").addEventListener("click", openComposer);

  els.modalContent.addEventListener("submit", (event) => {
    const form = event.target.closest("[data-reply-form]");
    if (!form) return;
    event.preventDefault();

    const thread = threads.find((item) => item.id === form.dataset.replyForm);
    const reply = form.elements.reply.value.trim();
    if (!thread || !reply) return;

    thread.comments.push({
      author: { en: i18n.en.you, th: i18n.th.you },
      avatar: "https://i.pravatar.cc/120?img=32",
      text: { en: reply, th: reply },
    });
    thread.replies += 1;
    thread.score += 2;
    thread.heat = Math.min(100, thread.heat + 4);
    playTone("send");
    showToast(t("replyAdded"));
    openThread(thread.id);
  });

  els.composerForm.addEventListener("submit", (event) => {
    event.preventDefault();
    createThread(new FormData(els.composerForm));
  });

  els.soundToggle.addEventListener("click", () => setSound(!state.sound, true));
  els.themeButton.addEventListener("click", () => {
    const nextTheme = state.theme === "sunrise" ? "night" : "sunrise";
    setTheme(nextTheme);
    playTone("tap");
  });
  els.languageToggle.addEventListener("click", () => {
    setLanguage(state.lang === "en" ? "th" : "en");
    playTone("tap");
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeThread();
      closeComposer();
    }
  });
}

