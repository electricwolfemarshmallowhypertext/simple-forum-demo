function toggleReaction(threadId, reaction, event) {
  const thread = threads.find((item) => item.id === threadId);
  if (!thread) return;

  const key = `${threadId}:${reaction}`;
  const active = state.reacted.has(key);
  thread.reactions[reaction] += active ? -1 : 1;
  thread.score += active ? -1 : 1;

  if (active) {
    state.reacted.delete(key);
    playTone("tap");
  } else {
    state.reacted.add(key);
    playTone("pop");
    popParticles(event.clientX, event.clientY, channelById(thread.channel).color);
  }

  saveReacted();
  renderThreads();
}

