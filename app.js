function getFilteredThreads() {
  const query = state.query.trim().toLowerCase();
  return threads
    .filter((thread) => state.channel === "all" || thread.channel === state.channel)
    .filter((thread) => state.tag === "all" || thread.tag === state.tag)
    .filter((thread) => {
      if (!query) return true;
      return [
        getText(thread.title),
        getText(thread.excerpt),
        thread.title.en,
        thread.title.th,
        thread.excerpt.en,
        thread.excerpt.th,
        getText(thread.author),
        tagLabel(thread.tag),
        thread.tag,
        channelName(thread.channel),
      ]
        .join(" ")
        .toLowerCase()
        .includes(query);
    })
    .sort((a, b) => {
      if (state.sort === "new") return b.createdAt - a.createdAt;
      if (state.sort === "top") return b.score - a.score;
      return b.heat - a.heat;
    });
}

