function setupCanvas() {
  const canvas = document.querySelector("#signalCanvas");
  const context = canvas.getContext("2d");
  const points = Array.from({ length: 80 }, () => ({
    x: Math.random(),
    y: Math.random(),
    vx: (Math.random() - 0.5) * 0.00045,
    vy: (Math.random() - 0.5) * 0.00045,
    r: 1 + Math.random() * 2.5,
  }));

  function resize() {
    const ratio = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = Math.floor(innerWidth * ratio);
    canvas.height = Math.floor(innerHeight * ratio);
    canvas.style.width = `${innerWidth}px`;
    canvas.style.height = `${innerHeight}px`;
    context.setTransform(ratio, 0, 0, ratio, 0, 0);
  }

  function frame() {
    context.clearRect(0, 0, innerWidth, innerHeight);
    context.lineWidth = 1;

    points.forEach((point) => {
      point.x += point.vx;
      point.y += point.vy;
      if (point.x < 0 || point.x > 1) point.vx *= -1;
      if (point.y < 0 || point.y > 1) point.vy *= -1;
    });

    for (let a = 0; a < points.length; a += 1) {
      const first = points[a];
      const fx = first.x * innerWidth;
      const fy = first.y * innerHeight;

      context.beginPath();
      context.fillStyle = state.theme === "sunrise" ? "rgba(12, 169, 130, 0.34)" : "rgba(68, 241, 200, 0.34)";
      context.arc(fx, fy, first.r, 0, Math.PI * 2);
      context.fill();

      for (let b = a + 1; b < points.length; b += 1) {
        const second = points[b];
        const sx = second.x * innerWidth;
        const sy = second.y * innerHeight;
        const distance = Math.hypot(fx - sx, fy - sy);
        if (distance > 140) continue;

        const alpha = (1 - distance / 140) * 0.18;
        context.strokeStyle =
          state.theme === "sunrise" ? `rgba(8, 127, 189, ${alpha})` : `rgba(105, 199, 255, ${alpha})`;
        context.beginPath();
        context.moveTo(fx, fy);
        context.lineTo(sx, sy);
        context.stroke();
      }
    }

    requestAnimationFrame(frame);
  }

  resize();
  addEventListener("resize", resize);
  frame();
}

