function createThread(formData) {
  const channel = String(formData.get("channel"));
  const tag = String(formData.get("tag"));
  const title = String(formData.get("title")).trim();
  const excerpt = String(formData.get("excerpt")).trim();
  const channelInfo = channelById(channel);
  const newThread = {
    id: makeId(),
    channel,
    tag,
    title: { en: title, th: title },
    excerpt: { en: excerpt, th: excerpt },
    author: { en: t("you"), th: i18n.th.you },
    avatar: "https://i.pravatar.cc/120?img=32",
    replies: 0,
    views: 1,
    score: 1,
    heat: 88,
    createdAt: Date.now(),
    reactions: { like: 0, spark: 0, wow: 0 },
    comments: [
      {
        author: "Neon Forum",
        avatar: "https://i.pravatar.cc/120?img=15",
        text: { en: i18n.en.systemComment, th: i18n.th.systemComment },
      },
    ],
  };

  threads = [newThread, ...threads.map((thread) => ({ ...thread, heat: Math.max(18, thread.heat - 3) }))];
  channelInfo.count += 1;
  state.channel = "all";
  state.tag = "all";
  state.sort = "new";
  document.querySelectorAll(".segment").forEach((segment) => {
    segment.classList.toggle("active", segment.dataset.sort === "new");
  });
  closeComposer();
  els.composerForm.reset();
  renderAll();
  showToast(t("threadPublished"));
  playTone("send");
}

